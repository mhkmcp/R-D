"""Render docs/M5_results.md — the headline tables, per SPEC §9's reporting rules."""

import json
from pathlib import Path

import pandas as pd

from fidnn.eval import stats
from fidnn.tables import md

HEADLINE_ALPHAS = (0.01, 0.001)


def _hypothesis_h1(headline: pd.DataFrame, track: str, alpha: float) -> str:
    """H1: fused SVDD vs the best output-only score, per track — rejected if the CI includes 0."""
    rows = headline[(headline.track == track) & (headline.alpha == alpha)]
    fused = rows[rows.detector == "D2"]
    baseline = rows[rows.get("family", pd.Series(index=rows.index)).eq("output_only")]
    if fused.empty or baseline.empty:
        return f"- Track {track} @ α={alpha:.1%}: not evaluable (missing fused or baseline rows)."
    best = baseline.loc[baseline.tpr.idxmax()]
    diff = stats.paired_difference(fused.tpr.to_numpy(), [best.tpr] * len(fused))
    return (f"- **Track {track} @ α={alpha:.1%}:** D2 TPR {fused.tpr.mean():.3f} vs best "
            f"output-only ({best.detector}) {best.tpr:.3f} — difference {diff['difference']:+.3f} "
            f"[{diff['ci_low']:+.3f}, {diff['ci_high']:+.3f}], **{diff['verdict']}**.")


def write(results_dir: Path, out: Path, overhead_doc: str = "docs/M0_throughput.md") -> None:
    heads = [pd.read_parquet(p) for p in sorted(results_dir.glob("*_headline.parquet"))]
    if not heads:
        raise FileNotFoundError(f"no *_headline.parquet under {results_dir}")
    headline = pd.concat(heads, ignore_index=True)
    breaks = [pd.read_parquet(p) for p in sorted(results_dir.glob("*_breakdowns.parquet"))]
    breakdowns = pd.concat(breaks, ignore_index=True) if breaks else pd.DataFrame()
    sides = [json.loads(p.read_text()) for p in sorted(results_dir.glob("*_eval.json"))]
    seeds = sorted({s["seed"] for s in sides})

    main = headline[headline.alpha.isin(HEADLINE_ALPHAS)]
    over_seeds = stats.aggregate_over_seeds(
        main, "tpr", ["model", "precision", "tap_set", "detector", "track", "alpha"])
    enough = over_seeds.enough_seeds.all() if len(over_seeds) else False
    seed_note = ("" if enough else
                 f"\n> ⚠️ **Not yet reportable.** SPEC §9.5 (C4) requires ≥ {stats.MIN_SEEDS} seeds "
                 f"per configuration; these tables cover {len(seeds)} ({seeds}).")

    gen_cols = ["model", "precision", "detector", "track", "alpha", "tpr", "n_fault"]
    gen_table = (headline[headline.subset.eq("fault_gen")][gen_cols] if "subset" in headline
                 else pd.DataFrame({"note": ["no fault_gen rows"]}))

    sections = []
    for axis in sorted(breakdowns.axis.unique()) if len(breakdowns) else []:
        g = breakdowns[(breakdowns.axis == axis) & (breakdowns.alpha == 0.01)]
        cols = ["detector", "track", "value", "tpr", "measured_fpr", "auroc", "aupr", "n_fault"]
        sections.append(f"### By {axis}\n\n{md(g[cols].sort_values(['detector', 'track', 'value']))}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"""# M-5 — Detection results

**Milestone:** M-5 (SPEC §12) · **Seeds:** {seeds} · **Generated by** `fidnn report`
{seed_note}

Tracks S (MASKED ∪ DEGRADED) and H (SDC ∪ CRASH) are reported separately and never merged (§4.3).
Detection quality is read together with the overhead figures in [`{overhead_doc}`]({Path(overhead_doc).name})
— C5 makes them one result, not two.

## Headline — TPR at calibrated thresholds, per track

{md(over_seeds, floatfmt=".4f")}

`mean` is over seeds with a bootstrap 95 % CI; `alpha` is the a-priori nominal FPR (§8, C3).

## Hypothesis H1 — multi-layer fusion vs output-only scores

{chr(10).join(_hypothesis_h1(headline, t, a) for t in ("S", "H") for a in HEADLINE_ALPHAS)}

A CI that includes 0 is written as "no detected difference", never as a win (§9.5).

## Unseen configurations (`fault_gen`)

{md(gen_table, floatfmt=".4f")}

## Mandatory breakdowns (α = 1 %)

{chr(10).join(sections) if sections else "No breakdown rows were produced."}
""")
    print(f"[m5] wrote {out}")
